/* DOM-shaped fixture only; no browser, permissions, account or microphone. */
import { runInNewContext } from 'node:vm';
import { readFileSync } from 'node:fs';
import { describe, expect, it, vi } from 'vitest';
import { doWidgetScript, DO_DISTRIBUTION_ORIGIN } from './distribution';
function fixture() {
  const nodes: any[] = [];
  const events: Record<string, ((event: any) => void)[]> = {};
  const make = (tag: string): any => {
    const handlers: Record<string, ((event: any) => void)[]> = {};
    const attrs: Record<string, string> = {};
    const node: any = { tagName: tag.toUpperCase(), style: {}, children: [], hidden: false, value: '',
      append(...children: any[]) { this.children.push(...children); }, setAttribute(k: string, v: string) { attrs[k] = v; }, attrs,
      addEventListener(k: string, fn: any) { (handlers[k] ??= []).push(fn); },
      fire(k: string, event: any = {}) { for (const fn of handlers[k] ?? []) fn(event); },
      getBoundingClientRect() { return { left: parseFloat(this.style.left) || 20, top: parseFloat(this.style.top) || 20, width: 300, height: 300 }; },
      focus: vi.fn(), attachShadow: () => make('shadow'), classList: { toggle: () => true },
      setPointerCapture: vi.fn(), hasPointerCapture: () => true, releasePointerCapture: vi.fn(),
      contentWindow: { postMessage: vi.fn() },
    };
    nodes.push(node); return node;
  };
  const body = make('body');
  const document = { body, createElement: make, createElementNS: (_: string, tag: string) => make(tag), addEventListener: vi.fn(), removeEventListener: vi.fn() };
  const win: any = { getSelection: () => null, addEventListener(k: string, fn: any) { (events[k] ??= []).push(fn); }, removeEventListener: vi.fn() };
  win.self = win; win.top = win;
  const saved = new Map();
  runInNewContext(doWidgetScript(DO_DISTRIBUTION_ORIGIN), { window: win, document, location: { origin: 'https://public.invalid', pathname: '/page' }, innerWidth: 800, innerHeight: 600,
    localStorage: { getItem: (k: string) => saved.get(k) ?? null, setItem: (k: string, v: string) => saved.set(k, v) },
    URL, crypto: { randomUUID: () => 'fixture-id' }, requestAnimationFrame: (fn: any) => { fn(); return 1; }, cancelAnimationFrame: vi.fn(), navigator: {}, CustomEvent: class {},
  });
  return { win, nodes, frame: nodes.find(n => n.tagName === 'IFRAME'), panel: nodes.find(n => n.attrs.role === 'dialog'),
    byText: (text: string) => nodes.find(n => n.textContent === text),
    message: (data: any) => events.message.forEach(fn => fn({ data, source: nodes.find(n => n.tagName === 'IFRAME').contentWindow, origin: DO_DISTRIBUTION_ORIGIN })), saved };
}
describe('actual generated floating companion in a DOM-shaped fixture', () => {
  it('opens Talk inside the same frame and minimises without destroying conversation', () => {
    const f = fixture(); f.byText('Talk here').fire('click');
    expect(f.panel.hidden).toBe(false); expect(f.frame.src).toBe(`${DO_DISTRIBUTION_ORIGIN}/do/widget`);
    f.message({ type: 'assembl-do:ready' });
    expect(f.frame.contentWindow.postMessage).toHaveBeenCalledWith({ type: 'assembl-do:entry', entry: 'talk' }, DO_DISTRIBUTION_ORIGIN);
    f.win.assemblDo.close(); expect(f.panel.hidden).toBe(true);
    expect(f.frame.contentWindow.postMessage).toHaveBeenCalledWith({ type: 'assembl-do:hidden' }, DO_DISTRIBUTION_ORIGIN);
    f.win.assemblDo.open(); expect(f.panel.hidden).toBe(false); expect(f.nodes.filter(n => n.tagName === 'IFRAME')).toHaveLength(1);
    expect(f.frame.attrs.allow).toBe(`microphone ${DO_DISTRIBUTION_ORIGIN}; clipboard-write; web-share`);
  });
  it('moves with keyboard and offers bounded text only after explicit Use', () => {
    const f = fixture(); f.win.assemblDo.open({ text: 'Fictional public text', title: 'Public example', url: 'https://public.invalid/private-path?token=secret#fragment' });
    f.message({ type: 'assembl-do:ready' }); expect(f.frame.contentWindow.postMessage).not.toHaveBeenCalled();
    f.byText('Use in DO').fire('click');
    const payload = f.frame.contentWindow.postMessage.mock.calls[0][0];
    expect(payload.text).toBe('Fictional public text'); expect(payload.url).toBe('https://public.invalid');
    expect(JSON.stringify(payload)).not.toContain('secret');
    const grab = f.nodes.find(n => n.attrs['aria-label']?.startsWith('Move DO'));
    grab.fire('keydown', { key: 'ArrowRight', preventDefault: vi.fn() });
    expect(f.panel.style.left).toBe('44px'); expect(f.saved.size).toBe(1);
  });
  it('keeps generated extension exactly aligned with canonical shared source', () => {
    expect(readFileSync('apps/do/extension/floating.js', 'utf8')).toBe("'use strict';\n// Generated by scripts/generate-do-companion.ts.\n" + doWidgetScript(DO_DISTRIBUTION_ORIGIN) + '\n');
  });
});
